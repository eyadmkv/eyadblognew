import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';

const read = (path) => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
const html = await read('dist/post/post_1782051283429/index.html');
const home = await read('dist/index.html');
const about = await read('dist/about/index.html');
const rss = await read('dist/rss.xml');
const robots = await read('dist/robots.txt');
const articleDirs = await readdir(new URL('../dist/post', import.meta.url));
const sourceFiles = (await readdir(new URL('../src/content/blog', import.meta.url))).filter((f) => f.endsWith('.md'));
const source = await Promise.all(sourceFiles.map((f) => read(`src/content/blog/${f}`)));
const publishedIds = source.filter((s) => /^status: "published"$/m.test(s)).map((s) => s.match(/^id: "([^"]+)"$/m)?.[1]);
const sitemapIndex = await read('dist/sitemap.xml');
const sitemapPath = sitemapIndex.match(/<loc>[^<]*\/(sitemap-[^<]+\.xml)<\/loc>/)?.[1];
assert.ok(sitemapPath, 'sitemap index points to sitemap file');
const sitemap = await read(`dist/${sitemapPath}`);
const jsonLd = html.match(/<script type="application\/ld\+json">(.*?)<\/script>/s)?.[1];
assert.ok(jsonLd, 'article JSON-LD exists');
const schema = JSON.parse(jsonLd);
assert.equal(articleDirs.length, publishedIds.length);
assert.ok(!articleDirs.some((id) => !publishedIds.includes(id)), 'drafts are excluded');
assert.equal(new Set(publishedIds).size, publishedIds.length, 'published IDs are unique');
assert.ok(home.includes('rel="canonical" href="https://eyadblog.vercel.app/"'));
assert.ok(about.includes('rel="canonical" href="https://eyadblog.vercel.app/about"'));
assert.ok(html.includes('https://eyadblog.vercel.app/post/post_1782051283429'));
assert.ok(html.includes('الشطرنج: حرب صامتة على 64 مربع'));
assert.ok(html.includes('الشطرنج مش مجرد لعبة'));
assert.equal(schema['@type'], 'BlogPosting');
assert.equal(schema.inLanguage, 'ar');
assert.ok(sitemap.includes('https://eyadblog.vercel.app/'));
assert.ok(sitemap.includes('https://eyadblog.vercel.app/about'));
assert.ok(publishedIds.every((id) => sitemap.includes(`/post/${id}`)));
assert.ok(!sitemap.includes('localhost'));
assert.ok(robots.includes('https://eyadblog.vercel.app/sitemap.xml'));
assert.ok(rss.includes('<item>'));
assert.ok(publishedIds.every((id) => rss.includes(`https://eyadblog.vercel.app/post/${id}`)));
assert.ok((await read('dist/google99ddf784f6b767b5.html')).includes('google-site-verification'));
console.log(`SEO output verified: ${publishedIds.length} published routes, valid article JSON-LD, sitemap, RSS, robots, and verification file.`);
